#!/bin/sh
# Regenerates docs/wire.md: real requests against examples/todo with curl (HTTP/2), real output.
set -eu
cd "$(dirname "$0")/.."
PORT=18443
PORT=$PORT node examples/todo/server.ts > /dev/null &
SERVER=$!
trap 'kill $SERVER 2>/dev/null' EXIT
sleep 1
B="https://localhost:$PORT"
C="curl -s --http2 --cacert certs/cert.pem"
show() { # $1 = title, $2 = shell command; prints the command and its (header-filtered) output
  printf '### %s\n\n```console\n$ %s\n' "$1" "$2"
  sh -c "$2" 2>&1 | grep -viE '^(date|content-length|alt-svc):' | sed 's/\r$//'
  printf '```\n\n'
}
{
  cat <<'MD'
# apü on the wire

Real requests against `examples/todo` (HTTP/2 via curl), generated by `docs/wire.sh`.
`i=` is the RFC 8785 canonical JSON input, `s=` a field selection.

MD
  show "Discovery: RFC 9727 API catalog" "$C $B/.well-known/api-catalog"
  show "Unsafe op: POST + Idempotency-Key" "$C -i -X POST -H 'content-type: application/json' -H 'idempotency-key: \"demo-1\"' -d '{\"title\":\"buy milk\"}' $B/todos.create"
  show "Retry with the same key: replayed, not executed again" "$C -i -X POST -H 'content-type: application/json' -H 'idempotency-key: \"demo-1\"' -d '{\"title\":\"buy milk\"}' $B/todos.create"
  show "Safe op: GET with canonical input — ETag, Cache-Control, Accept-Query" "$C -i '$B/todos.get?i=%7B%22id%22%3A1%7D'"
  ETAG=$($C -i "$B/todos.get?i=%7B%22id%22%3A1%7D" | grep -i '^etag:' | cut -d' ' -f2 | tr -d '\r')
  show "Conditional GET → 304" "$C -i -H 'if-none-match: $ETAG' '$B/todos.get?i=%7B%22id%22%3A1%7D'"
  show "Field selection" "$C '$B/todos.get?i=%7B%22id%22%3A1%7D&s=title'"
  show "QUERY (RFC 10008) for reads with a body" "$C -i -X QUERY -H 'content-type: application/json' -d '{\"id\":1}' $B/todos.get"
  show "Validation error → 400 problem details (RFC 9457)" "$C -i -X POST -H 'content-type: application/json' -d '{\"title\":\"\"}' $B/todos.create"
  show "Unknown op → 404" "$C -i $B/nope.nothing"
  show "Resumable stream rendered as SSE (debug view): checkpoints become id: lines" "$C -N --max-time 1 -H 'accept: text/event-stream' $B/todos.changes || true"
  show "Pipelined batch: create + complete in one round trip (binary frames, hex)" "$C -X POST -H 'content-type: application/json' -d '{\"calls\":[{\"op\":\"todos.create\",\"in\":{\"title\":\"ship\"},\"key\":\"b1\"},{\"op\":\"todos.complete\",\"in\":{\"id\":{\"\$ref\":[0,\"id\"]}},\"key\":\"b2\"}]}' '$B/\$batch' | xxd | head -12"
} > docs/wire.md
