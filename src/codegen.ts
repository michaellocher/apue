// Manifest → TypeScript API definition (`defineApi` + `t.*`), so clients in other code bases get
// the same typed client and validation without importing the server's sources. Web-only.

import type { OpHttp, ProblemRef } from './docs.ts';

type JsonSchema = Record<string, any>;

export interface ManifestOp {
  effect: string;
  stream: string;
  description?: string;
  input: JsonSchema;
  output: JsonSchema;
  cache?: Record<string, unknown>;
  deprecated?: { since: string; sunset?: string; link?: string };
  resumable?: boolean;
  invalidates?: string[];
  /** Derived documentation (src/docs.ts) — not needed to generate code. */
  http?: OpHttp;
  errors?: ProblemRef[];
  example?: { input?: unknown; output?: unknown };
}

export interface Manifest {
  apue: string;
  ops: Record<string, ManifestOp>;
  /** Derived documentation and server limits — not needed to generate code. */
  http?: Record<string, unknown>;
  errors?: ProblemRef[];
  limits?: Record<string, unknown>;
}

export interface CodegenOptions {
  /**
   * Where the generated module imports apü from: a package name (e.g. `@michaellocher/apue` — one import from
   * the package) or the path of a source checkout's runtime directory (`./apue/src` — imports
   * `api.ts` and `schema.ts` from it).
   */
  runtime: string;
  /** Where the manifest came from (for the header comment). */
  source?: string;
  exportName?: string;
}

export function generateApi(manifest: Manifest, options: CodegenOptions): string {
  const runtime = options.runtime.replace(/\/$/, '');
  const ops = Object.entries(manifest.ops).map(([name, def]) => {
    const fields = [
      `effect: ${JSON.stringify(def.effect)}`,
      ...(def.stream !== 'none' ? [`stream: ${JSON.stringify(def.stream)}`] : []),
      ...(def.resumable ? ['resumable: true'] : []),
      `input: ${schemaCode(def.input)}`,
      `output: ${schemaCode(def.output)}`,
      ...(def.cache ? [`cache: ${JSON.stringify(def.cache)}`] : []),
      ...(def.invalidates ? [`invalidates: ${JSON.stringify(def.invalidates)}`] : []),
      ...(def.deprecated ? [`deprecated: ${deprecationCode(def.deprecated)}`] : []),
      ...(def.description ? [`description: ${JSON.stringify(def.description)}`] : []),
    ];
    return `  ${JSON.stringify(name)}: op({ ${fields.join(', ')} }),`;
  });
  return [
    `// Generated by apue-types from ${options.source ?? 'a manifest'} (${manifest.apue}). Do not edit.`,
    ...(/^(\.|\/|[a-z][a-z0-9+.-]*:)/i.test(runtime)
      ? [`import { defineApi, op } from '${runtime}/api.ts';`, `import { t } from '${runtime}/schema.ts';`]
      : [`import { defineApi, op, t } from '${runtime}';`]),
    '',
    `export const ${options.exportName ?? 'api'} = defineApi({`,
    ...ops,
    '});',
    '',
  ].join('\n');
}

function deprecationCode(d: NonNullable<ManifestOp['deprecated']>): string {
  const parts = [`since: new Date(${JSON.stringify(d.since)})`];
  if (d.sunset) parts.push(`sunset: new Date(${JSON.stringify(d.sunset)})`);
  if (d.link) parts.push(`link: ${JSON.stringify(d.link)}`);
  return `{ ${parts.join(', ')} }`;
}

const ALLOWED: Record<string, readonly string[]> = {
  string: ['type', 'minLength', 'maxLength', 'pattern', 'x-apue-flags', 'enum', 'contentEncoding', 'contentMediaType', 'x-apue-transfer', 'x-apue-max-size'],
  integer: ['type', 'minimum', 'maximum'],
  number: ['type', 'minimum', 'maximum'],
  boolean: ['type'],
  null: ['type'],
  array: ['type', 'items', 'maxItems'],
  object: ['type', 'properties', 'required', 'x-apue-transfer', 'contentMediaType'],
};

/**
 * The subset of JSON Schema that apü's schema builder emits. Anything else is an error rather
 * than silently dropped — a dropped keyword would weaken validation on the client.
 */
export function schemaCode(schema: JsonSchema): string {
  const unsupported = () => new Error(`unsupported JSON Schema: ${JSON.stringify(schema).slice(0, 120)}`);
  if (typeof schema.type === 'string') {
    const allowed = ALLOWED[schema.type];
    if (!allowed || Object.keys(schema).some((key) => !allowed.includes(key))) throw unsupported();
  } else if (!('anyOf' in schema && Object.keys(schema).length === 1) && Object.keys(schema).length > 0) {
    throw unsupported();
  }
  const opts = (entries: Array<[string, unknown]>) => {
    const present = entries.filter(([, v]) => v !== undefined);
    return present.length ? `{ ${present.map(([k, v]) => `${k}: ${v instanceof RegExp ? v.toString() : JSON.stringify(v)}`).join(', ')} }` : '';
  };
  if (Object.keys(schema).length === 0) return 't.unknown()';
  if (Array.isArray(schema.anyOf) && schema.anyOf.length === 2 && schema.anyOf[1]?.type === 'null') return `t.nullable(${schemaCode(schema.anyOf[0])})`;
  switch (schema.type) {
    case 'null':
      return 't.void()';
    case 'boolean':
      return 't.boolean()';
    case 'string':
      if (schema['x-apue-transfer'] === 'blob-frames') return 't.bytes()';
      if (schema['x-apue-transfer'] === 'upload') return `t.file(${opts([['max', schema['x-apue-max-size']]])})`;
      if (Array.isArray(schema.enum)) return `t.enum(${JSON.stringify(schema.enum)})`;
      return `t.string(${opts([['min', schema.minLength], ['max', schema.maxLength], ['pattern', schema.pattern === undefined ? undefined : new RegExp(schema.pattern, schema['x-apue-flags'] ?? '')]])})`;
    case 'integer':
      return `t.number(${opts([['int', true], ['min', schema.minimum], ['max', schema.maximum]])})`;
    case 'number':
      return `t.number(${opts([['min', schema.minimum], ['max', schema.maximum]])})`;
    case 'array':
      return `t.array(${schemaCode(schema.items ?? {})}${schema.maxItems === undefined ? '' : `, { max: ${schema.maxItems} }`})`;
    case 'object': {
      // t.download(): the reference's fields are fixed by the type, only the media type varies.
      if (schema['x-apue-transfer'] === 'download') return `t.download(${opts([['type', schema.contentMediaType]])})`;
      if (schema['x-apue-transfer'] !== undefined || schema.contentMediaType !== undefined) throw unsupported();
      const required = new Set<string>(schema.required ?? []);
      const fields = Object.entries<JsonSchema>(schema.properties ?? {}).map(([key, value]) => {
        const code = schemaCode(value);
        return `${JSON.stringify(key)}: ${required.has(key) ? code : `t.optional(${code})`}`;
      });
      return `t.object({ ${fields.join(', ')} })`;
    }
    default:
      throw new Error(`unsupported JSON Schema: ${JSON.stringify(schema).slice(0, 120)}`);
  }
}
