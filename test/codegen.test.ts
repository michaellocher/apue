// Manifest → generated API definition → identical manifest (and it works as a typed client contract).
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { pathToFileURL } from 'node:url';
import { promisify } from 'node:util';
import { defineApi, op, type Api } from '../src/api.ts';
import { ApueClient } from '../src/client.ts';
import { generateApi, schemaCode, type Manifest } from '../src/codegen.ts';
import { t } from '../src/schema.ts';
import { buildManifest, type Handlers } from '../src/server.ts';
import { http2Transport } from '../src/transport-http2.ts';
import { startServer, testCert } from './helpers.ts';

const runtime = pathToFileURL(join(import.meta.dirname, '..', 'src')).href;

const Rich = t.object({
  id: t.string({ min: 1, max: 36, pattern: /^[a-z0-9-]+$/ }),
  age: t.optional(t.number({ int: true, min: 0, max: 150 })),
  score: t.number({ min: -1 }),
  role: t.enum(['admin', 'member']),
  tags: t.array(t.string(), { max: 10 }),
  manager: t.nullable(t.object({ id: t.string() })),
  avatar: t.optional(t.bytes()),
  extra: t.unknown(),
  active: t.boolean(),
  code: t.string({ pattern: /^[a-z]+\/\d+$/iu }), // flags and a slash survive the round trip (review finding)
});

const original = defineApi({
  'users.get': op({ effect: 'safe', input: t.object({ id: t.string() }), output: Rich, cache: { maxAge: 60, staleWhileRevalidate: 30 }, description: 'One user' }),
  'users.old': op({ effect: 'safe', input: t.void(), output: t.string(), deprecated: { since: new Date('2026-01-01T00:00:00Z'), sunset: new Date('2027-01-01T00:00:00Z'), link: 'https://example.com/m' } }),
  'users.watch': op({ effect: 'safe', stream: 'server', resumable: true, input: t.void(), output: t.array(Rich) }),
  'files.put': op({ effect: 'unsafe', stream: 'client', input: t.object({ data: t.bytes() }), output: t.number() }),
  'users.rename': op({ effect: 'unsafe', input: t.object({ id: t.string() }), output: t.string(), invalidates: ['users'] }),
  'users.cached': op({ effect: 'safe', input: t.void(), output: t.string(), cache: { maxAge: 5, cdnMaxAge: 600, groups: ['users'] } }),
  'chat': op({ effect: 'idempotent', stream: 'bidi', input: t.string(), output: t.nullable(t.string()) }),
});

async function importGenerated(code: string): Promise<Api> {
  const dir = mkdtempSync(join(tmpdir(), 'apue-codegen-'));
  const file = join(dir, 'api.ts');
  writeFileSync(file, code);
  return ((await import(pathToFileURL(file).href)) as { api: Api }).api;
}

test('round trip: manifest → generated code → identical manifest', async () => {
  const manifest = buildManifest(original) as unknown as Manifest;
  const code = generateApi(manifest, { runtime, source: 'test' });
  assert.match(code, /^\/\/ Generated by apue-types from test \(draft-00\)\. Do not edit\./);
  const generated = await importGenerated(code);
  assert.deepEqual(buildManifest(generated), buildManifest(original));
});

test('regex flags are restored by codegen, so generated clients validate like the server', async () => {
  const code = schemaCode({ type: 'string', pattern: '^[a-z]+\\/\\d+$', 'x-apue-flags': 'iu' });
  assert.equal(code, 't.string({ pattern: /^[a-z]+\\/\\d+$/iu })');
  const schema = (await importGenerated(`import { t } from '${runtime}/schema.ts';\nexport const api = ${code};\n`)) as unknown as { parse(v: unknown): unknown };
  assert.equal(schema.parse('ABC/12'), 'ABC/12');
});

test('unsupported JSON Schema is an error, not a silent unknown', () => {
  assert.throws(() => schemaCode({ type: 'string', format: 'date-time' }), /unsupported JSON Schema/);
  assert.throws(() => schemaCode({ type: 'object', properties: {}, additionalProperties: false }), /unsupported JSON Schema/);
  assert.throws(() => schemaCode({ oneOf: [{ type: 'string' }, { type: 'number' }] }), /unsupported JSON Schema/);
  assert.throws(() => schemaCode({ anyOf: [{ type: 'string' }, { type: 'number' }] }), /unsupported JSON Schema/);
  assert.throws(() => schemaCode({ type: 'date' }), /unsupported JSON Schema/);
  assert.equal(schemaCode({}), 't.unknown()');
});

test('CLI against a running server; the generated contract drives a typed client', async () => {
  const handlers: Handlers<typeof original> = {
    'users.get': ({ id }) => ({ id, score: 1, role: 'admin', tags: [], manager: null, extra: { any: 'thing' }, active: true, code: 'AB/1' }),
    'users.old': () => 'old',
    'users.watch': async function* () {},
    'files.put': async (inputs) => {
      let n = 0;
      for await (const { data } of inputs) n += data.byteLength;
      return n;
    },
    'users.rename': ({ id }) => id,
    'users.cached': () => 'c',
    'chat': async function* (inputs) {
      for await (const s of inputs) yield s;
    },
  };
  const server = await startServer(original, handlers);
  const dir = mkdtempSync(join(tmpdir(), 'apue-cli-'));
  writeFileSync(join(dir, 'ca.pem'), testCert().cert);
  const out = join(dir, 'api.ts');
  await promisify(execFile)(process.execPath, [join(import.meta.dirname, '..', 'bin', 'apue-types.ts'), server.url, '--runtime', runtime, '--ca', join(dir, 'ca.pem'), '--out', out]);
  const generated = (await import(pathToFileURL(out).href)) as { api: typeof original };
  const client = new ApueClient(generated.api, http2Transport(server.url, { ca: testCert().cert }));
  assert.deepEqual(await client.call('users.get', { id: 'ab-1' }), { id: 'ab-1', score: 1, role: 'admin', tags: [], manager: null, extra: { any: 'thing' }, active: true, code: 'AB/1' });
  // The generated schemas validate on the client too: no request is sent for invalid input.
  await assert.rejects(client.call('users.get', { id: 42 as unknown as string }), (e: { status: number }) => e.status === 400);
  await client.close();
  await server.close();
});
